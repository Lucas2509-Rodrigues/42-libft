#include "libft.h"

int	ft_atoi(const char *str)
{
	int		i;
	long	resultado;
	int		sign;

	sign = 1;
	i = 0;
	resultado = 0;
	while (str[i] == ' ' || (str[i] >= 9 && str[i] <= 13))
		i++;
	if (str[i] == '-' || str[i] == '+')
	{
		if (str[i] == '-')
			sign = -sign;
		i++;
	}
	while (ft_isdigit(str[i]))
	{
		resultado = (resultado * 10) + str[i] - '0';
		i++;
	}
	return ((int)(resultado * sign));
}

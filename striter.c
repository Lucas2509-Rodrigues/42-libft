#include "libft.h"

void	ft_striter(char *s, void (*f)(char *))
{
	int	i;

	if (!s)
		return ;
	i = 0;
	if (f)
	{
		while (s[i] != '\0')
		{
			f(&s[i]);
			i++;
		}
	}
}
